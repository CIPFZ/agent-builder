package shell

import (
	"testing"
	"unicode/utf8"
)

func TestNormalizeCommandOutputConvertsGBK(t *testing.T) {
	t.Parallel()

	gbkPingPrefix := string([]byte{
		0xd5, 0xfd, 0xd4, 0xda, 0x20, 0x50, 0x69, 0x6e, 0x67, 0x20,
		0x77, 0x77, 0x77, 0x2e, 0x62, 0x61, 0x69, 0x64, 0x75, 0x2e,
		0x63, 0x6f, 0x6d, 0x20, 0x5b, 0x31, 0x39, 0x38, 0x2e, 0x31,
		0x38, 0x2e, 0x30, 0x2e, 0x31, 0x38, 0x34, 0x5d, 0x20, 0xbe,
		0xdf, 0xd3, 0xd0, 0x20, 0x33, 0x32, 0x20, 0xd7, 0xd6, 0xbd,
		0xda, 0xb5, 0xc4, 0xca, 0xfd, 0xbe, 0xdd, 0x3a,
	})

	got := normalizeCommandOutput(gbkPingPrefix)
	if !utf8.ValidString(got) {
		t.Fatalf("decoded output is not valid UTF-8: %q", got)
	}
	if got != "正在 Ping www.baidu.com [198.18.0.184] 具有 32 字节的数据:" {
		t.Fatalf("normalizeCommandOutput() = %q", got)
	}
}
